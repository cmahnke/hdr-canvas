// Builds the inlined WASM gain kernel (`src/wasm/kernel.ts`) from `assembly/`.
// Fails if the module needs any imports (it must stay self-contained) or if
// the smoke test below disagrees with the expected f16 bit patterns.
import { execFileSync } from "child_process";
import { createHash } from "crypto";
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const asc = process.platform === "win32" ? "asc.cmd" : "asc";
const wasmPath = join(root, "build", "gain.wasm");
const outPath = join(root, "src", "wasm", "kernel.ts");

const EXPECTED_EXPORTS = ["memory", "ABI_VERSION", "arena_reset", "arena_alloc", "gain_run"];

execFileSync(join(root, "node_modules", ".bin", asc), ["--config", "asconfig.json", "--target", "release"], {
  cwd: root,
  stdio: "inherit"
});

const bytes = readFileSync(wasmPath);
const mod = new WebAssembly.Module(bytes);

const imports = WebAssembly.Module.imports(mod);
if (imports.length !== 0) {
  throw new Error(`gain.wasm must be import-free, got: ${JSON.stringify(imports)}`);
}
const names = WebAssembly.Module.exports(mod).map((e) => e.name);
for (const name of EXPECTED_EXPORTS) {
  if (!names.includes(name)) {
    throw new Error(`gain.wasm is missing export "${name}", got: ${names.join(", ")}`);
  }
}

// Smoke test: 1.0 * 2 must be exactly 2.0 (0x4000), alpha untouched.
const instance = new WebAssembly.Instance(mod, {});
const exports = instance.exports;
exports.arena_reset();
const ptr = exports.arena_alloc(8);
let view = new Uint16Array(exports.memory.buffer);
view.set([0x3c00, 0x3c00, 0x3c00, 0x3c00], ptr / 2);
exports.gain_run(ptr, 1, 2, 2, 2, 1);
view = new Uint16Array(exports.memory.buffer);
const got = Array.from(view.slice(ptr / 2, ptr / 2 + 4));
const want = [0x4000, 0x4000, 0x4000, 0x3c00];
if (got.some((v, i) => v !== want[i])) {
  throw new Error(`gain.wasm smoke test failed: got ${got.map((v) => v.toString(16))}, want 4000,4000,4000,3c00`);
}
if (exports.ABI_VERSION.value !== 1) {
  throw new Error(`gain.wasm ABI mismatch: got ${exports.ABI_VERSION.value}, want 1`);
}

const base64 = Buffer.from(bytes).toString("base64");
const sha256 = createHash("sha256").update(bytes).digest("hex");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// GENERATED by scripts/build-wasm.mjs from assembly/gain.ts - do not edit.
// sha256(gain.wasm) = ${sha256}
export const WASM_ABI = 1;
export const WASM_BYTE_LENGTH = ${bytes.length};
export const WASM_BASE64 = "${base64}";
`
);
// Keep the generated file prettier-stable so `prettier --check .` passes.
const prettier = process.platform === "win32" ? "prettier.cmd" : "prettier";
execFileSync(join(root, "node_modules", ".bin", prettier), ["--write", outPath], { cwd: root, stdio: "inherit" });
console.log(`Wrote ${outPath} (${bytes.length} bytes wasm, ${base64.length} bytes base64, sha256 ${sha256.slice(0, 12)}...)`);
